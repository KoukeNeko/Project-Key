# Draws the input method icon for Linux and macOS as Windows draws its own at
# build time (platforms/windows/build.ps1): a white ㄅ in Microsoft JhengHei UI
# Bold, 0.62 of the shape's height, on the accent color #14806f with corners a
# fifth of its size. Run on Windows, which has the font; commit the results.
#   platforms/linux/fcitx-projectkey.svg   64x64, the ㄅ as outlines so no font is needed
#   platforms/linux/fcitx-projectkey-symbolic.svg   the same in one color, the ㄅ cut out
#   platforms/macos/Resources/icon.tiff    a 22x16 pt input source icon: the shape fills the frame, as
#                                          macOS's own ones do, at 1x and 2x
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Join-Path $PSScriptRoot '..\..'
$accent = [Drawing.Color]::FromArgb(0x14, 0x80, 0x6f)
$bopomofo = [string][char]0x3105

# The ㄅ as a path, centered in a box as build.ps1 centers it (nudged down 4% of the size).
function Glyph([float]$x, [float]$y, [float]$width, [float]$height) {
  $path = [Drawing.Drawing2D.GraphicsPath]::new()
  $format = [Drawing.StringFormat]::new(); $format.Alignment = 'Center'; $format.LineAlignment = 'Center'
  $family = [Drawing.FontFamily]::new('Microsoft JhengHei UI')
  $path.AddString($bopomofo, $family, [int][Drawing.FontStyle]::Bold, $height * 0.62,
    [Drawing.RectangleF]::new($x, $y + $height * 0.04, $width, $height), $format)
  $path
}

function RoundedRect([float]$x, [float]$y, [float]$width, [float]$height, [float]$r) {
  $path = [Drawing.Drawing2D.GraphicsPath]::new()
  $path.AddArc($x, $y, 2 * $r, 2 * $r, 180, 90); $path.AddArc($x + $width - 2 * $r, $y, 2 * $r, 2 * $r, 270, 90)
  $path.AddArc($x + $width - 2 * $r, $y + $height - 2 * $r, 2 * $r, 2 * $r, 0, 90); $path.AddArc($x, $y + $height - 2 * $r, 2 * $r, 2 * $r, 90, 90)
  $path.CloseFigure()
  $path
}

# Linux: SVG path data from the glyph's outline.
$size = 64
$glyph = Glyph 0 0 $size $size
$points = $glyph.PathPoints; $types = $glyph.PathTypes
$d = [Text.StringBuilder]::new()
$f = { param($p) '{0:0.##},{1:0.##}' -f $p.X, $p.Y }
for ($i = 0; $i -lt $points.Count; $i++) {
  switch ($types[$i] -band 7) {
    0 { [void]$d.Append('M' + (& $f $points[$i])) }
    1 { [void]$d.Append('L' + (& $f $points[$i])) }
    3 { [void]$d.Append('C' + (& $f $points[$i]) + ' ' + (& $f $points[$i + 1]) + ' ' + (& $f $points[$i + 2])); $i += 2 }
  }
  if ($types[$i] -band 0x80) { [void]$d.Append('Z') }
}
$svg = @"
<svg xmlns="http://www.w3.org/2000/svg" width="$size" height="$size" viewBox="0 0 $size $size">
  <!-- Generated by tools/icon/make-icons.ps1. -->
  <rect width="$size" height="$size" rx="$($size / 5)" fill="#14806f"/>
  <path fill="#ffffff" d="$d"/>
</svg>
"@
[IO.File]::WriteAllText((Join-Path $root 'platforms\linux\fcitx-projectkey.svg'), $svg.Replace("`r", '') + "`n")
# The one-color icon for panels that tint their icons (COSMIC's): the shape with the ㄅ cut out.
$r = $size / 5
$shape = "M$r,0H$($size - $r)A$r,$r 0 0 1 $size,$($r)V$($size - $r)A$r,$r 0 0 1 $($size - $r),$($size)H$($r)A$r,$r 0 0 1 0,$($size - $r)V$($r)A$r,$r 0 0 1 $r,0Z"
$symbolic = @"
<svg xmlns="http://www.w3.org/2000/svg" width="$size" height="$size" viewBox="0 0 $size $size">
  <!-- Generated by tools/icon/make-icons.ps1. -->
  <path fill="#bebebe" fill-rule="evenodd" d="$shape$d"/>
</svg>
"@
[IO.File]::WriteAllText((Join-Path $root 'platforms\linux\fcitx-projectkey-symbolic.svg'), $symbolic.Replace("`r", '') + "`n")

# macOS: the 22x16 pt frame at 1x (72 dpi) and 2x (144 dpi).
function MacFrame([int]$scale) {
  $bitmap = [Drawing.Bitmap]::new(22 * $scale, 16 * $scale)
  $bitmap.SetResolution(72 * $scale, 72 * $scale)
  $g = [Drawing.Graphics]::FromImage($bitmap)
  $g.SmoothingMode = 'AntiAlias'
  $g.ScaleTransform($scale, $scale)
  $g.FillPath([Drawing.SolidBrush]::new($accent), (RoundedRect 0 0 22 16 3))
  $g.FillPath([Drawing.Brushes]::White, (Glyph 0 0 22 16))
  $g.Dispose()
  $bitmap
}
$tiff = [Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object { $_.MimeType -eq 'image/tiff' }
$params = [Drawing.Imaging.EncoderParameters]::new(1)
$params.Param[0] = [Drawing.Imaging.EncoderParameter]::new([Drawing.Imaging.Encoder]::SaveFlag, [long][Drawing.Imaging.EncoderValue]::MultiFrame)
$first = MacFrame 2
$first.Save((Join-Path $root 'platforms\macos\Resources\icon.tiff'), $tiff, $params)
$params.Param[0] = [Drawing.Imaging.EncoderParameter]::new([Drawing.Imaging.Encoder]::SaveFlag, [long][Drawing.Imaging.EncoderValue]::FrameDimensionPage)
$first.SaveAdd((MacFrame 1), $params)
$params.Param[0] = [Drawing.Imaging.EncoderParameter]::new([Drawing.Imaging.Encoder]::SaveFlag, [long][Drawing.Imaging.EncoderValue]::Flush)
$first.SaveAdd($params)
$first.Dispose()

# The Fcitx5 theme (platforms/linux/theme): the candidate window's colors and corners.
$theme = Join-Path $root 'platforms\linux\theme'
function ThemeImage([string]$name, [int]$width, [int]$height, [scriptblock]$draw) {
  $bitmap = [Drawing.Bitmap]::new($width, $height)
  $g = [Drawing.Graphics]::FromImage($bitmap)
  $g.SmoothingMode = 'AntiAlias'
  & $draw $g
  $g.Dispose()
  $bitmap.Save((Join-Path $theme $name), [Drawing.Imaging.ImageFormat]::Png)
  $bitmap.Dispose()
}
$muted = [Drawing.Color]::FromArgb(0x8e, 0x9a, 0xa3)
# The window: 8px corners, a 1px edge. Fcitx5 stretches the middle and keeps the 8px corners.
# Translucent over the blur behind it (theme.conf's EnableBlur), as Panel.cpp draws over one:
# the background at 0.85, the edge at 0.6.
ThemeImage 'panel.png' 24 24 {
  param($g)
  $shape = RoundedRect 0.5 0.5 23 23 7.5
  $g.FillPath([Drawing.SolidBrush]::new([Drawing.Color]::FromArgb(217, 0x23, 0x28, 0x2c)), $shape)
  $g.DrawPath([Drawing.Pen]::new([Drawing.Color]::FromArgb(153, 0x34, 0x3b, 0x40), 1), $shape)
}
# The selection: 4px corners in the accent color, big enough for the 11/5/6 margins it is cut at.
ThemeImage 'highlight.png' 24 24 { param($g) $g.FillPath([Drawing.SolidBrush]::new($accent), (RoundedRect 0 0 24 24 4)) }
$chevron = {
  param($g, [float[]]$xs, [float]$top, [float]$mid, [float]$bottom)
  $pen = [Drawing.Pen]::new($muted, 2); $pen.StartCap = 'Round'; $pen.EndCap = 'Round'; $pen.LineJoin = 'Round'
  $g.DrawLines($pen, [Drawing.PointF[]]@([Drawing.PointF]::new($xs[0], $top), [Drawing.PointF]::new($xs[1], $mid), [Drawing.PointF]::new($xs[0], $bottom)))
}
ThemeImage 'prev.png' 16 24 { param($g) & $chevron $g @(10, 6) 8 12 16 }
ThemeImage 'next.png' 16 24 { param($g) & $chevron $g @(6, 10) 8 12 16 }
ThemeImage 'arrow.png' 6 12 { param($g) & $chevron $g @(1.5, 4.5) 3 6 9 }
ThemeImage 'radio.png' 24 24 { param($g) $g.FillEllipse([Drawing.SolidBrush]::new([Drawing.Color]::FromArgb(0x3f, 0xb9, 0xa3)), 8, 8, 8, 8) }